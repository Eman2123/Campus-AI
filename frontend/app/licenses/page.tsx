import type { Metadata } from "next";

import { LegalPage } from "@/components/site/LegalPage";
import data from "@/lib/licenses.generated.json";

export const metadata: Metadata = {
  title: "Open-source licences",
  description: "The open-source software Campus AI is built with, and the licence each package comes under.",
  alternates: { canonical: "/licenses" },
};

type Pkg = { name: string; version: string; license: string; source: "frontend" | "backend" };
const packages = data.packages as Pkg[];

// Licences whose terms ask for more than a notice (e.g. share changes to the library itself).
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|SSPL|EUPL|CC-BY-SA)/i;

function countByLicense(list: Pkg[]) {
  const counts = new Map<string, number>();
  for (const p of list) counts.set(p.license, (counts.get(p.license) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1]);
}

function PackageList({ title, list }: { title: string; list: Pkg[] }) {
  return (
    <details className="border-2 border-brand-black bg-brand-white p-3">
      <summary className="cursor-pointer font-pixel text-lg font-bold">
        {title} ({list.length})
      </summary>
      <ul className="mt-3 max-h-96 space-y-1 overflow-y-auto text-sm">
        {list.map((p) => (
          <li key={`${p.source}-${p.name}-${p.version}`} className="flex justify-between gap-3">
            <span className="break-all">
              {p.name} <span className="text-muted-onPaper">{p.version}</span>
            </span>
            <span className="shrink-0 text-right">{p.license}</span>
          </li>
        ))}
      </ul>
    </details>
  );
}

// Generated by scripts/generate_licenses.py: re-run it whenever dependencies change.
export default function LicensesPage() {
  const frontend = packages.filter((p) => p.source === "frontend");
  const backend = packages.filter((p) => p.source === "backend");
  const copyleft = packages.filter((p) => COPYLEFT.test(p.license));

  return (
    <LegalPage title="Open-source licences" updated={data.generated}>
      <p>
        Campus AI is built on the work of many open-source projects. We are grateful to their authors. This page lists the
        {" "}
        {packages.length} packages that ship with the service and the licence each one comes under. Each package keeps its own
        licence and copyright; nothing here changes them.
      </p>

      <h2>Licences at a glance</h2>
      <ul>
        {countByLicense(packages).map(([license, count]) => (
          <li key={license}>
            <strong>{license}</strong>: {count} package{count === 1 ? "" : "s"}
          </li>
        ))}
      </ul>

      {copyleft.length > 0 && (
        <>
          <h2>Libraries with sharing conditions</h2>
          <p>
            A few libraries come under licences (such as LGPL or MPL) that apply to the library&rsquo;s own files. We use them
            unmodified, as separately installed packages; you are free to get them from their original projects:
          </p>
          <ul>
            {copyleft.map((p) => (
              <li key={`${p.source}-${p.name}`}>
                {p.name} {p.version}: {p.license}
              </li>
            ))}
          </ul>
        </>
      )}

      <h2>Every package</h2>
      <div className="space-y-3">
        <PackageList title="Website (frontend)" list={frontend} />
        <PackageList title="Server (backend)" list={backend} />
      </div>
    </LegalPage>
  );
}
